# Pixel cat sprite builder (original art, inspired by the reference look). Grid 40x29, sprite origin offset (2,4).
W, H, OX, OY = 40, 29, 2, 4

def rrect(x0, y0, x1, y1, cut=1):
    cells = set()
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            ok = True
            for cx, cy in ((x0, y0), (x1, y0), (x0, y1), (x1, y1)):
                if abs(x - cx) + abs(y - cy) < cut:
                    ok = False
            if ok:
                cells.add((x, y))
    return cells

def line_thick(p0, p1, steps):
    cells = set()
    (x0, y0), (x1, y1) = p0, p1
    for i in range(steps + 1):
        t = i / steps
        x = round(x0 + (x1 - x0) * t); y = round(y0 + (y1 - y0) * t)
        for dx, dy in ((0, 0), (1, 0), (0, 1)):
            cells.add((x + dx, y + dy))
    return cells

def put(grid, x, y, ch):
    X, Y = x + OX, y + OY
    if 0 <= X < W and 0 <= Y < H:
        grid[Y][X] = ch

def add_shape(grid, cells, fill, outline='k'):
    for (x, y) in cells:
        put(grid, x, y, fill)
    for (x, y) in cells:
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if n not in cells:
                put(grid, n[0], n[1], outline)

def build_frame(frame):
    g = [['.'] * W for _ in range(H)]
    # tail (behind body)
    ty = 1 if frame == 1 else 0
    tail = line_thick((6, 12 + ty), (2, 8 + ty), 4)
    add_shape(g, tail, 'g')
    # back legs
    sh = 1 if frame == 1 else 0
    for lx in (9 + sh, 15 + sh):
        add_shape(g, {(lx + i, 21 + j) for i in range(3) for j in range(2)}, 'g')
    # body
    add_shape(g, rrect(8, 2, 27, 19, 2), 'c')
    for (x, y) in rrect(10, 4, 25, 17, 2):
        put(g, x, y, 'f')
    # frosting accents: stars (z) and shine (y)
    for (x, y) in [(12, 4), (17, 6), (22, 5), (11, 8), (14, 11), (19, 9), (12, 14), (16, 13), (24, 4), (15, 16), (21, 7)]:
        put(g, x, y, 'z')
    for (x, y) in [(10, 5), (11, 5), (11, 6), (12, 7), (13, 8), (14, 9), (15, 10), (16, 11)]:
        put(g, x, y, 'y')
    # sprinkles
    for (x, y) in [(12, 6), (16, 5), (20, 6), (23, 5), (13, 9), (17, 11), (11, 12), (15, 15), (19, 13), (12, 16), (22, 9)]:
        put(g, x, y, 's')
    # head with ears
    head = rrect(21, 10, 34, 20, 1)
    for r in range(4):
        for c in range(r + 1):
            head.add((21 + c, 6 + r))
            head.add((34 - c, 6 + r))
    add_shape(g, head, 'g')
    # front legs
    for lx in (22 - sh, 30 - sh):
        add_shape(g, {(lx + i, 22 + j) for i in range(3) for j in range(2)}, 'g')
    # re-draw head bottom outline over leg tops (legs drawn after head would cover); redraw head outline row 21
    for x in range(21, 35):
        put(g, x, 21, 'k')
    # face
    for (x, y, ch) in [(24, 13, 'w'), (25, 13, 'e'), (24, 14, 'e'), (25, 14, 'e'),
                       (30, 13, 'w'), (31, 13, 'e'), (30, 14, 'e'), (31, 14, 'e'),
                       (27, 15, 'p'), (28, 15, 'p'),
                       (26, 16, 'e'), (29, 16, 'e'), (27, 17, 'e'), (28, 17, 'e'),
                       (22, 16, 'p'), (23, 16, 'p'), (22, 17, 'p'), (23, 17, 'p'),
                       (32, 16, 'p'), (33, 16, 'p'), (32, 17, 'p'), (33, 17, 'p')]:
        put(g, x, y, ch)
    return [''.join(r) for r in g]

